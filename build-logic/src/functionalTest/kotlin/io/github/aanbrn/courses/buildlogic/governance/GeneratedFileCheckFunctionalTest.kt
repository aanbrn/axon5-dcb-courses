package io.github.aanbrn.courses.buildlogic.governance

import io.github.aanbrn.courses.buildlogic.GradleFixture
import io.kotest.assertions.withClue
import io.kotest.matchers.collections.shouldBeIn
import io.kotest.matchers.collections.shouldContain
import io.kotest.matchers.string.shouldContain
import java.nio.file.Files
import java.nio.file.Path
import org.gradle.testkit.runner.TaskOutcome
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.io.TempDir

/**
 * Proves `checkComposeVersions`, the generated-file freshness check, keeps `compose/versions.env` in step with the
 * catalog.
 */
class GeneratedFileCheckFunctionalTest {
    @TempDir lateinit var projectDir: Path

    private val fixture by lazy { GradleFixture.governance(projectDir) }

    @Test
    fun `a versions file equal to the rendering of the catalog images passes`() {
        fixture.file(VERSIONS_FILE, expectedVersions())

        val result = fixture.run(TASK)

        result.task(":$TASK")?.outcome shouldBeIn GradleFixture.PASSED
    }

    @Test
    fun `a stale digest fails naming the file and the command that regenerates it`() {
        fixture.file(
            VERSIONS_FILE,
            expectedVersions().replace(Regex("sha256:[0-9a-f]{64}"), "sha256:" + "0".repeat(64)),
        )

        val output = fixture.runAndFail(TASK).output

        output shouldContain "compose/versions.env is stale; run ./gradlew generateComposeVersions"
    }

    @Test
    fun `a versions file that lacks an image line is stale`() {
        val withoutPostgres =
            expectedVersions().lines().filterNot { it.startsWith("POSTGRES_IMAGE=") }.joinToString("\n")
        fixture.file(VERSIONS_FILE, withoutPostgres)

        val output = fixture.runAndFail(TASK).output

        output shouldContain "compose/versions.env is stale; run ./gradlew generateComposeVersions"
    }

    @Test
    fun `a missing versions file fails naming the file`() {
        val output = fixture.runAndFail(TASK).output

        output shouldContain "compose/versions.env"
    }

    @Test
    fun `a second run with unchanged inputs is up to date and a later edit is still reported`() {
        fixture.file(VERSIONS_FILE, expectedVersions())
        fixture.run(TASK)

        val second = fixture.run(TASK).task(":$TASK")?.outcome

        withClue("second run outcome") { listOf(TaskOutcome.UP_TO_DATE, TaskOutcome.FROM_CACHE) shouldContain second }
        fixture.file(VERSIONS_FILE, expectedVersions() + "EXTRA_IMAGE=extra:1\n")
        fixture.runAndFail(TASK).output shouldContain "compose/versions.env is stale"
    }

    /** The file `generateComposeVersions` writes for the images of the repository's own catalog. */
    private fun expectedVersions(): String {
        val catalog = Files.readString(Path.of(checkNotNull(System.getProperty("catalog"))))
        val lines =
            listOf("axonserver", "postgres").map { name ->
                val reference =
                    checkNotNull(Regex("""(?m)^image-$name = "([^"]+)"$""").find(catalog)) {
                            "image-$name is not in the catalog"
                        }
                        .groupValues[1]
                "${name.uppercase()}_IMAGE=$reference"
            }
        return (listOf(HEADER) + lines).joinToString(separator = "\n", postfix = "\n")
    }

    private companion object {
        const val TASK = "checkComposeVersions"
        const val VERSIONS_FILE = "compose/versions.env"
        const val HEADER =
            "# Generated by ./gradlew generateComposeVersions from gradle/libs.versions.toml; do not edit."
    }
}
