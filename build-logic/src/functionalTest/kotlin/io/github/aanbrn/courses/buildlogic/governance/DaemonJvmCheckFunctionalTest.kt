package io.github.aanbrn.courses.buildlogic.governance

import io.github.aanbrn.courses.buildlogic.GradleFixture
import io.kotest.assertions.withClue
import io.kotest.matchers.collections.shouldBeIn
import io.kotest.matchers.collections.shouldContain
import io.kotest.matchers.string.shouldContain
import java.nio.file.Path
import org.gradle.testkit.runner.TaskOutcome
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.io.TempDir

/** Proves `checkDaemonJvm` keeps `.java-version` and the daemon JVM criteria in step. */
class DaemonJvmCheckFunctionalTest {
    @TempDir lateinit var projectDir: Path

    private val fixture by lazy { GradleFixture.governance(projectDir) }

    private fun properties(version: String) =
        fixture.file(
            "gradle/gradle-daemon-jvm.properties",
            "#This file is generated by :updateDaemonJvm\ntoolchainVersion=$version\n",
        )

    @Test
    fun `equal majors pass`() {
        fixture.file(".java-version", "25\n")
        properties("25")

        val result = fixture.run("checkDaemonJvm")

        result.task(":checkDaemonJvm")?.outcome shouldBeIn GradleFixture.PASSED
    }

    @Test
    fun `a java-version with minor parts is compared by its major`() {
        fixture.file(".java-version", "25.0.1\n")
        properties("25")

        fixture.run("checkDaemonJvm").task(":checkDaemonJvm")?.outcome shouldBeIn GradleFixture.PASSED
    }

    @Test
    fun `different majors fail and name the regeneration command`() {
        fixture.file(".java-version", "25\n")
        properties("21")

        val output = fixture.runAndFail("checkDaemonJvm").output

        output shouldContain "updateDaemonJvm"
        output shouldContain "toolchainVersion=21"
        output shouldContain "JDK 25"
    }

    @Test
    fun `a missing java-version file fails naming the file`() {
        properties("25")

        fixture.runAndFail("checkDaemonJvm").output shouldContain ".java-version is missing"
    }

    @Test
    fun `an empty java-version file fails naming the file`() {
        fixture.file(".java-version", "  \n")
        properties("25")

        fixture.runAndFail("checkDaemonJvm").output shouldContain ".java-version is empty"
    }

    @Test
    fun `a non-numeric java-version fails naming the file`() {
        fixture.file(".java-version", "latest\n")
        properties("25")

        fixture.runAndFail("checkDaemonJvm").output shouldContain ".java-version must start with a numeric JDK major"
    }

    @Test
    fun `a missing daemon JVM properties file fails with the generation command`() {
        fixture.file(".java-version", "25\n")

        val output = fixture.runAndFail("checkDaemonJvm").output

        output shouldContain "gradle-daemon-jvm.properties is missing"
        output shouldContain "updateDaemonJvm"
    }

    @Test
    fun `a daemon JVM properties file without toolchainVersion fails`() {
        fixture.file(".java-version", "25\n")
        fixture.file("gradle/gradle-daemon-jvm.properties", "other=1\n")

        fixture.runAndFail("checkDaemonJvm").output shouldContain "has no toolchainVersion"
    }

    @Test
    fun `a second run with unchanged inputs is up to date and drift is still caught`() {
        fixture.file(".java-version", "25\n")
        properties("25")
        fixture.run("checkDaemonJvm")

        val second = fixture.run("checkDaemonJvm").task(":checkDaemonJvm")?.outcome

        withClue("second run outcome") {
            listOf(TaskOutcome.UP_TO_DATE, TaskOutcome.FROM_CACHE) shouldContain second
        }
        fixture.file(".java-version", "21\n")
        fixture.runAndFail("checkDaemonJvm").output shouldContain "updateDaemonJvm"
    }
}
