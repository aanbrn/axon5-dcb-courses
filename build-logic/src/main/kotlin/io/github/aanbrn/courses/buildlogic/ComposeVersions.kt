package io.github.aanbrn.courses.buildlogic

import org.gradle.api.DefaultTask
import org.gradle.api.GradleException
import org.gradle.api.artifacts.VersionCatalog
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.provider.MapProperty
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputFile
import org.gradle.api.tasks.TaskAction

/**
 * The text of `compose/versions.env`, the one file through which the container images of the version catalog reach
 * Docker Compose (INFRA-09).
 *
 * The image set and the rendering live in this one place on purpose: [GenerateComposeVersions] writes the rendering of
 * [images] and `checkComposeVersions` compares the committed file with exactly the same text, so the generator and the
 * freshness check cannot disagree.
 */
object ComposeVersions {
    /** The header line of the generated file. */
    const val HEADER = "# Generated by ./gradlew generateComposeVersions from gradle/libs.versions.toml; do not edit."

    /**
     * Short names of the `image-*` catalog entries that are pinned for test JVMs only and are therefore not compose
     * images.
     *
     * `ryuk` is Testcontainers' resource reaper, which `courses.test-suites` sets through
     * `TESTCONTAINERS_RYUK_CONTAINER_IMAGE`; no compose file runs it. Every other `image-*` entry is a compose image by
     * default, so a new compose image is rendered and checked without a build-logic change, and excluding an entry is a
     * visible, reviewed edit of this set.
     */
    val TEST_ONLY_IMAGES: Set<String> = setOf("ryuk")

    /**
     * Derives the compose images from [catalog]: every version alias whose first segment is `image`, except the
     * [TEST_ONLY_IMAGES].
     *
     * The alias is split on `.`, `-` and `_`, so the result does not depend on Gradle's dot normalisation of catalog
     * aliases. The short name is the remaining segments joined with `_`, so `image-otel-lgtm` becomes `otel_lgtm`,
     * which [render] writes as `OTEL_LGTM_IMAGE`, the `[A-Z0-9_]+_IMAGE` variable form the compose files interpolate.
     *
     * This is the single source of the image set for both `generateComposeVersions` and `checkComposeVersions`, so they
     * cannot disagree on it, as [render] already guarantees for the text.
     *
     * @param catalog the `libs` version catalog
     * @return full image references (tag and digest) by short name
     * @throws GradleException when an image entry has no plain required version, such as one given with `strictly`
     */
    fun images(catalog: VersionCatalog): Map<String, String> =
        catalog.versionAliases
            .mapNotNull { alias ->
                val segments = alias.split('.', '-', '_')
                if (segments.first() == "image" && segments.size > 1) alias to segments.drop(1).joinToString("_")
                else null
            }
            .filterNot { (_, name) -> name in TEST_ONLY_IMAGES }
            .associate { (alias, name) ->
                val reference = catalog.findVersion(alias).get().requiredVersion
                if (reference.isBlank()) {
                    throw GradleException(
                        "The catalog entry '$alias' has no plain required version; a compose image must be a " +
                            "single tag-and-digest string",
                    )
                }
                name to reference
            }

    /**
     * Renders the env file for [images].
     *
     * @param images full image references (tag and digest) by short name, such as `axonserver`
     * @return the [HEADER] line and one `<NAME>_IMAGE=<reference>` line per image, sorted by name, ending with a
     *   newline
     */
    fun render(images: Map<String, String>): String =
        images.toSortedMap().entries.joinToString(
            separator = "\n",
            prefix = "$HEADER\n",
            postfix = "\n",
        ) { (name, reference) ->
            "${name.uppercase()}_IMAGE=$reference"
        }
}

/**
 * Writes `compose/versions.env` from the image references of the version catalog.
 *
 * Compose files hold no image literal. They interpolate `${<NAME>_IMAGE}`, one variable for every compose image of the
 * catalog (see [ComposeVersions.images]), which Compose reads from the committed output of this task, so a fresh clone
 * runs `docker compose up` without Gradle.
 */
@CacheableTask
abstract class GenerateComposeVersions : DefaultTask() {

    /** Full image references (tag and digest) by short name, such as `axonserver`. */
    @get:Input abstract val images: MapProperty<String, String>

    /** The env file that is written, `compose/versions.env`. */
    @get:OutputFile abstract val target: RegularFileProperty

    /** Writes the rendering of [images] to [target]. */
    @TaskAction
    fun generate() {
        target.get().asFile.apply {
            parentFile.mkdirs()
            writeText(ComposeVersions.render(images.get()))
        }
    }
}
